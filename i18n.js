function i18nHasCn(s) { return /[\u4e00-\u9fff]/.test(String(s == null ? '' : s)); }

function i18nPunct(out) {
  const punct = { '，': ', ', '；': '; ', '：': ': ', '（': ' (', '）': ')', '【': '[', '】': ']', '、': ', ', '。': '. ', '｜': ' | ', '＜': '<', '＞': '>', '≤': '<=', '≥': '>=' };
  Object.keys(punct).forEach(k => { if (out.indexOf(k) >= 0) out = out.split(k).join(punct[k]); });
  // 清理英文中多余空格：标点前空格、重复空格、句末空格
  out = out.replace(/\s+([,;:.)\]])/g, '$1')
           .replace(/([([\s])\s+/g, '$1')
           .replace(/ {2,}/g, ' ')
           .replace(/\s+\./g, '.')
           .replace(/\[\s+/g, '[').replace(/\s+\]/g, ']')
           .trim();
  return out;
}

function i18nConvert(s) {
  const src = String(s == null ? '' : s);
  if (!i18nHasCn(src)) return src;
  // 1) exact whole-string match
  const norm = src.replace(/^[\s\u3000]+|[\s\u3000]+$/g, '').replace(/[。;；,，]+$/, '');
  if (Object.prototype.hasOwnProperty.call(I18N_DICT, src)) return I18N_DICT[src];
  if (norm !== src && Object.prototype.hasOwnProperty.call(I18N_DICT, norm)) {
    return i18nPunct(I18N_DICT[norm] + (/[。；;]$/.test(src) ? '.' : ''));
  }
  let out = src;
  const isLong = src.length > 10 || /[。；，]/.test(src);

  // 2a) knowledge-base full sentences (chain / mechanism / verify)
  for (const k of I18N_KB_SENTENCE_KEYS) {
    if (out.indexOf(k) >= 0) out = out.split(k).join(I18N_DICT[k]);
  }
  // 2b) professional phrase layer — longest first, natural word order
  for (let i = 0; i < I18N_PHRASE_KEYS.length; i++) {
    const k = I18N_PHRASE_KEYS[i];
    if (out.indexOf(k) >= 0) out = out.split(k).join(' ' + I18N_PHRASES[k] + ' ');
  }
  // 2c) battery-industry terminology — longest first
  for (let i = 0; i < I18N_TERM_KEYS.length; i++) {
    const k = I18N_TERM_KEYS[i];
    if (out.indexOf(k) >= 0) out = out.split(k).join(' ' + I18N_TERMS[k] + ' ');
  }
  // 2d) general dictionary multi-character entries
  for (let i = 0; i < I18N_KEYS.length; i++) {
    const k = I18N_KEYS[i];
    if (k.length < 2 || I18N_SKIP_IN_TEXT.has(k)) continue;
    if (out.indexOf(k) >= 0) out = out.split(k).join(' ' + I18N_DICT[k] + ' ');
  }
  // 2e) generic connective words — only for free text, not UI labels
  if (isLong) {
    for (let i = 0; i < I18N_PROSE_KEYS.length; i++) {
      const k = I18N_PROSE_KEYS[i];
      if (out.indexOf(k) >= 0) out = out.split(k).join(I18N_PROSE[k]);
    }
  }
  // 2f) numeric + Chinese unit structures
  out = out.replace(/(\d+)\s*天/g, '$1 days')
           .replace(/(\d+)\s*片/g, '$1 pcs')
           .replace(/(\d+)\s*次/g, '$1 times')
           .replace(/(\d+)\s*号/g, ' No.$1')
           .replace(/(\d+)\s*月\s*(\d+)\s*日/g, '$1/$2')
           .replace(/(\d+)\s*项/g, '$1 items')
           .replace(/(\d+)\s*条/g, '$1 records')
           .replace(/s\s*\/\s*件/g, 's/pc')
           .replace(/(\d+)\s*件/g, '$1 pcs');
  return i18nPunct(out);
}

function i18nIsDataNode(node) {
  const p = node && node.parentElement;
  if (!p) return false;
  return /^(INPUT|TEXTAREA|SELECT|SCRIPT|STYLE)$/.test(p.tagName) || !!p.closest('[data-i18n-skip]');
}

function i18nTextNode(node) {
  if (!node || node.nodeType !== 3 || !i18nHasCn(node.nodeValue) || i18nIsDataNode(node)) return;
  if (!I18N_DONE.has(node)) {
    I18N_CACHE.push({ node: node, text: node.nodeValue });
    I18N_DONE.add(node);
  }
  const override = node.parentElement && node.parentElement.getAttribute('data-i18n-en');
  node.nodeValue = override || i18nConvert(node.nodeValue);
}

function i18nValueNode(el) {
  if (!el || !el.hasAttribute || !el.hasAttribute('data-i18n-value')) return;
  if (!el.__i18nVals) el.__i18nVals = {};
  const src = el.__i18nVals.value != null ? el.__i18nVals.value : el.value;
  if (src == null || src === '') return;
  if (el.__i18nVals.value == null) {
    el.__i18nVals.value = src;
    I18N_CACHE.push({ node: el, prop: 'value', text: src });
  }
  // Pre-generated professional English (structured) takes priority over
  // word-by-word conversion; avoids Chinese/English mixing in free text.
  const preEn = el.getAttribute('data-en-value');
  if (I18N_LANG === 'en') {
    el.value = preEn && preEn !== '' ? preEn : i18nConvert(src);
  } else {
    el.value = src;
  }
}

document.addEventListener('input', e => {
  const el = e.target;
  if (!el || !el.hasAttribute || !el.hasAttribute('data-i18n-value')) return;
  if (!el.__i18nVals) el.__i18nVals = {};
  // In EN mode the edited text is English; keep it in the EN slot so it is not lost.
  if (I18N_LANG === 'en' && el.getAttribute('data-en-value') != null) {
    el.setAttribute('data-en-value', el.value);
  } else {
    el.__i18nVals.value = el.value;
  }
});

function i18nVisibility() {
  const enOnly = document.querySelectorAll ? document.querySelectorAll('[data-i18n-en-only]') : [];
  for (let i = 0; i < enOnly.length; i++) enOnly[i].style.display = I18N_LANG === 'en' ? '' : 'none';
  const zhOnly = document.querySelectorAll ? document.querySelectorAll('[data-i18n-zh-only]') : [];
  for (let i = 0; i < zhOnly.length; i++) zhOnly[i].style.display = I18N_LANG === 'zh' ? '' : 'none';
}

function i18nApply(root) {
  if (I18N_LANG !== 'en') return;
  const base = root && root.nodeType === 1 ? root : document.body;
  if (!base) return;
  if (base.nodeType === 3) { i18nTextNode(base); return; }
  const walker = document.createTreeWalker(base, NodeFilter.SHOW_TEXT, null, false);
  let n;
  while ((n = walker.nextNode())) i18nTextNode(n);
  if (base.hasAttribute && base.hasAttribute('data-i18n-value')) i18nValueNode(base);
  const all = base.querySelectorAll ? base.querySelectorAll('*') : [];
  for (let v = 0; v < all.length; v++) i18nValueNode(all[v]);
  i18nVisibility();
  for (let i = 0; i < all.length; i++) {
    const el = all[i];
    I18N_ATTRS.forEach(attr => {
      const v = el.getAttribute(attr);
      if (!v || !i18nHasCn(v)) return;
      if (!el.__i18nAttrs) el.__i18nAttrs = {};
      if (!el.__i18nAttrs[attr]) {
        el.__i18nAttrs[attr] = v;
        I18N_CACHE.push({ node: el, attr: attr, text: v });
      }
      el.setAttribute(attr, i18nConvert(v));
    });
  }
}

function i18nApplyGuarded(fn) {
  if (!I18N_OBSERVER || I18N_LANG !== 'en') { fn(); return; }
  I18N_OBSERVER.disconnect();
  try { fn(); } finally { I18N_OBSERVER.observe(document.body, { childList: true, subtree: true, characterData: true }); }
}

function i18nObserve() {
  if (I18N_OBSERVER || !document.body) return;
  I18N_OBSERVER = new MutationObserver(muts => {
    if (I18N_LANG !== 'en') return;
    i18nApplyGuarded(() => {
      muts.forEach(m => {
        if (m.type === 'characterData') { i18nTextNode(m.target); return; }
        Array.prototype.forEach.call(m.addedNodes, node => {
          if (node.nodeType === 1) i18nApply(node);
          else if (node.nodeType === 3) i18nTextNode(node);
        });
      });
    });
  });
  I18N_OBSERVER.observe(document.body, { childList: true, subtree: true, characterData: true });
}

