function i18nInit() {
  let saved = 'zh';
  try { saved = localStorage.getItem('bcpms_lang') || 'zh'; } catch (e) {}
  // Optional ?lang=en / ?lang=zh override, useful for sharing a link in a fixed language.
  try {
    const q = new URLSearchParams(window.location.search).get('lang');
    if (q === 'en' || q === 'zh') saved = q;
  } catch (e) {}
  const btn = document.getElementById('btnLang');
  if (btn) btn.addEventListener('click', () => i18nSetLang(I18N_LANG === 'en' ? 'zh' : 'en'));
  i18nSetLang(saved);
}

