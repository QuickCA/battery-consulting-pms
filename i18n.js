function i18nSetLang(lang) {
  I18N_LANG = lang === 'en' ? 'en' : 'zh';
  try { localStorage.setItem('bcpms_lang', I18N_LANG); } catch (e) {}
  document.documentElement.lang = I18N_LANG === 'en' ? 'en' : 'zh-CN';
  document.title = I18N_LANG === 'en'
    ? 'Cell Consulting · Site Issue Closed-Loop Management'
    : '\u7535\u82af\u6280\u672f\u54a8\u8be2 \u00b7 \u73b0\u573a\u95ee\u9898\u95ed\u73af\u7ba1\u7406\u7cfb\u7edf';

  if (I18N_LANG === 'zh') {
    I18N_CACHE.forEach(e => {
      if (e.prop === 'value') { if (e.node) e.node.value = e.text; }
      else if (e.attr) { if (e.node.setAttribute) e.node.setAttribute(e.attr, e.text); }
      else if (e.node) e.node.nodeValue = e.text;
      I18N_DONE.delete(e.node);
    });
    I18N_CACHE.length = 0;
  } else {
    i18nApply(document.body);
    i18nObserve();
  }
  i18nVisibility();
  i18nUpdateButton();
  window.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang: I18N_LANG } }));
}

